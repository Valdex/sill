import Foundation

// The clipboard's later generations, the host's rules (Sources/SillHost/ClipboardRichPolicy.swift): what a
// subscription takes, what a look reads, each generation's kind 32 and its cap, generation 1 unchanged, a
// device's kind 32 as the pasteboard takes it, and the device's copied files kept on the Mac.
var failures = 0
var checks = 0
func check(_ ok: Bool, _ what: @autoclosure () -> String, line: Int = #line) {
    checks += 1
    if !ok { failures += 1; print("FAIL (line \(line)): \(what())") }
}
var rng = SystemRandomNumberGenerator()
typealias R = ClipboardRichPolicy
func data(_ s: String) -> Data { Data(s.utf8) }
func decode(_ d: Data?) -> Clipboard? { d.flatMap { Wire.decode(Clipboard.self, from: $0) } }
let png = Data([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 1, 2, 3])
let jpeg = Data([0xFF, 0xD8, 0xFF, 0xE0, 9])

// MARK: - The generation offered and subscriptions

check(R.offered(synthetic: false) == 3 && R.offered(synthetic: true) == 2, "a real host offers 3, a synthetic one 2 (it writes no file)")
check(R.accepts(after: data("{}"), current: nil, offered: 3) == 1, "`{}`: text alone")
check(R.accepts(after: data(#"{"accepts":3}"#), current: nil, offered: 3) == 3, "`{\"accepts\":3}`: files too")
check(R.accepts(after: data(#"{"accepts":2}"#), current: 3, offered: 3) == 2, "a bare subscription says it again")
check(R.accepts(after: data("{}"), current: 3, offered: 3) == 1, "`{}` again: back to text alone")
check(R.accepts(after: data(#"{"accepts":3}"#), current: nil, offered: 2) == 2, "never more than the host offers")
check(R.accepts(after: data(#"{"accepts":9}"#), current: nil, offered: 3) == 3 && R.accepts(after: data(#"{"accepts":0}"#), current: nil, offered: 3) == 1
      && R.accepts(after: data(#"{"accepts":-4}"#), current: nil, offered: 3) == 1, "held to 1 … offered")
check(R.accepts(after: data(#"{"text":"hi"}"#), current: 3, offered: 3) == 3, "a copy without `accepts` keeps the subscription")
check(R.accepts(after: data(#"{"text":"hi"}"#), current: nil, offered: 3) == 1, "a copy from a connection that never said: 1")
check(R.accepts(after: data(#"{"text":"hi","accepts":2}"#), current: 3, offered: 3) == 2, "a copy with `accepts` says it")
check(R.accepts(after: data(#"{"image":"iVBORw=="}"#), current: 2, offered: 3) == 2, "an image alone is a copy, not a bare subscription")
check(R.accepts(after: data(#"{"stop":true,"accepts":3}"#), current: 3, offered: 3) == nil && R.accepts(after: data("nope"), current: 2, offered: 3) == nil,
      "a stop or a payload that does not decode: ClipboardPolicy's")

// MARK: - What a look reads

let finder = ["public.file-url", "public.utf8-plain-text", "com.apple.icns", "public.tiff"]
check(R.reads(types: ["public.png", "public.html"], generation: 1).isEmpty, "generation 1 reads nothing more (ClipboardPolicy reads its text)")
check(R.reads(types: ["public.png", "public.tiff", "public.html", "public.rtf"], generation: 2) == [.png, .html, .rtf], "generation 2: the PNG, not the TIFF beside it")
check(R.reads(types: ["public.tiff"], generation: 2) == [.tiff], "a TIFF alone stands in")
check(R.reads(types: finder, generation: 3) == [.files], "Finder's copy for 3: the files, never their icon")
check(R.reads(types: finder, generation: 2).isEmpty, "Finder's copy for 2: the names as text only (no icon)")
check(R.reads(types: ["public.utf8-plain-text"], generation: 3).isEmpty, "text alone: nothing more")
check(R.concealed(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]) && R.concealed(types: ["org.nspasteboard.TransientType"])
      && R.concealed(types: ["com.agilebits.onepassword"]) && R.concealed(types: ["de.petermaurer.TransientPasteboardType"]),
      "concealed: nspasteboard.org's two markers, the older transient one, 1Password's")
check(!R.concealed(types: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"]) && !R.concealed(types: []),
      "an ordinary copy (or an app's generated one) is not concealed")

// MARK: - Each generation's kind 32

let rich = R.MacItem(text: "Hello", html: "<b>Hello</b>", rtf: data("{\\rtf1 Hello}"), png: png)
let r2 = R.payload(rich, generation: 2)
check(decode(r2.payload) == Clipboard(text: "Hello", image: png, html: "<b>Hello</b>", rtf: data("{\\rtf1 Hello}")) && r2.left.isEmpty,
      "generation 2: text, image, HTML and RTF")
check(R.payload(rich, generation: 1).payload == nil, "never for generation 1 (ClipboardPolicy's payload serves it)")
let offer = ClipboardFiles(offer: 77, files: [DragOffer.File(name: "a.pdf", size: 10), DragOffer.File(name: "Photos", size: 0, folder: true)])
let withFiles = R.MacItem(text: "a.pdf\nPhotos", files: offer)
check(decode(R.payload(withFiles, generation: 3).payload) == Clipboard(text: "a.pdf\nPhotos", files: offer), "generation 3: the files' offer and the names")
check(decode(R.payload(withFiles, generation: 2).payload) == Clipboard(text: "a.pdf\nPhotos"), "generation 2 never sees the offer")
check(R.payload(R.MacItem(files: offer), generation: 2).payload == nil, "files alone to generation 2: nothing")
check(R.payload(R.MacItem(files: ClipboardFiles(offer: 1, files: [])), generation: 3).payload == nil, "an offer of no file is nothing")
check(decode(R.payload(R.MacItem(text: "pw", concealed: true), generation: 2).payload) == Clipboard(text: "pw", concealed: true),
      "a concealed copy: `concealed` true")
check(!String(decoding: R.payload(R.MacItem(text: "x"), generation: 3).payload ?? Data(), as: UTF8.self).contains("concealed"),
      "an ordinary one leaves it out")
check(R.payload(R.MacItem(text: ""), generation: 2).payload == nil && R.payload(R.MacItem(), generation: 3).payload == nil, "nothing to send: nil")
let long = String(repeating: "a", count: Clipboard.maxTextBytes + 1)
let tl = R.payload(R.MacItem(text: long, html: "<p>x</p>"), generation: 2)
check(decode(tl.payload) == Clipboard(html: "<p>x</p>") && tl.left == [.textTooLong], "text over 256 KB left out, the rest goes")
// The cap: the image first, then RTF, HTML, the offer, the text.
let big = Data(repeating: 7, count: 3_200_000)            // 4.27 MB as base64: never fits beside anything
let bigImage = R.MacItem(text: "t", html: "<p>h</p>", rtf: data("{r}"), png: Data([0x89]) + big)
let capped = R.payload(bigImage, generation: 2)
check(decode(capped.payload) == Clipboard(text: "t", html: "<p>h</p>", rtf: data("{r}")) && capped.left == [.image], "an image over the 4 MiB cap goes first")
check((capped.payload?.count ?? .max) <= StreamMessage.maxOtherHostPayload, "the rest within it")
let fits = Data(repeating: 1, count: 3_000_000)          // 4,000,000 bytes of base64
let justFits = R.payload(R.MacItem(text: "t", png: fits), generation: 2)
check(justFits.left.isEmpty && (justFits.payload?.count ?? .max) <= StreamMessage.maxOtherHostPayload, "an image that fits stays (\(justFits.payload?.count ?? 0) bytes)")
let order = R.payload(R.MacItem(text: "t", html: String(repeating: "h", count: 2_100_000), rtf: Data(repeating: 2, count: 1_600_000), png: Data(repeating: 3, count: 900_000)), generation: 2)
check(order.left == [.image, .rtf] && decode(order.payload)?.html?.count == 2_100_000, "then the RTF, the HTML kept: \(order.left)")
let small = R.payload(R.MacItem(text: "t", html: "<p>h</p>", png: Data(repeating: 1, count: 1000)), generation: 2, cap: 600)
check(small.left == [.image] && decode(small.payload)?.html == "<p>h</p>", "a smaller cap: the same order (\(small.left))")
let tiny = R.payload(R.MacItem(text: "t", html: String(repeating: "h", count: 200), rtf: Data(repeating: 1, count: 200)), generation: 2, cap: 40)
check(tiny.left == [.rtf, .html] && decode(tiny.payload) == Clipboard(text: "t"), "the text last: \(tiny.left)")
// Random items: every payload decodes, fits its cap, carries only what its generation takes, keeps the text
// unless nothing else fits, and leaves out in the order image, RTF, HTML, files, text.
for _ in 0..<3_000 {
    let item = R.MacItem(text: Bool.random(using: &rng) ? String(repeating: "x", count: Int.random(in: 0...400, using: &rng)) : nil,
                         html: Bool.random(using: &rng) ? String(repeating: "<", count: Int.random(in: 0...400, using: &rng)) : nil,
                         rtf: Bool.random(using: &rng) ? Data(repeating: 5, count: Int.random(in: 0...400, using: &rng)) : nil,
                         png: Bool.random(using: &rng) ? Data(repeating: 6, count: Int.random(in: 0...400, using: &rng)) : nil,
                         files: Bool.random(using: &rng) ? offer : nil, concealed: Bool.random(using: &rng))
    let g = Int.random(in: 2...3, using: &rng), cap = Int.random(in: 30...2_000, using: &rng)
    let (p, left) = R.payload(item, generation: g, cap: cap)
    let rank: [R.Left: Int] = [.image: 0, .rtf: 1, .html: 2, .files: 3, .textTooLong: 4]
    let ranks = left.map { rank[$0]! }
    var ok = ranks == ranks.sorted() && Set(ranks).count == ranks.count
    if let p {
        let c = decode(p)
        ok = ok && c != nil && p.count <= cap && (g >= 3 || c?.files == nil) && c?.stop == nil && c?.accepts == nil
            && (c?.concealed == (item.concealed ? true : nil))
            && (c?.image == nil || left.isEmpty)        // the image goes only when nothing was left out
            && (c?.text != nil || item.text?.isEmpty != false || left.contains(.textTooLong))
    }
    if !ok { check(false, "random payload g\(g) cap \(cap): left \(left), \(p?.count ?? -1) bytes"); break }
}
check(true, "3,000 random items: within the cap, only their generation's fields, left out in order")

// Who gets what for one change: generation 1 exactly ClipboardPolicy's payload.
let textPayload = ClipboardPolicy.payload(text: "Hello")
let sent = R.sends(to: [("ipad", 1), ("pc", 3), ("mac", 2), ("old", 0)], textPayload: textPayload, item: rich)
check(sent.count == 4 && sent[0].0 == "ipad" && sent[0].1 == textPayload && sent[3].1 == textPayload, "generation 1 (and anything below): ClipboardPolicy's payload, byte for byte")
check(decode(sent[1].1)?.image == png && decode(sent[2].1)?.html == "<b>Hello</b>" && decode(sent[2].1)?.files == nil, "2 and 3 their own")
check(R.sends(to: [("ipad", 1), ("pc", 3)], textPayload: nil, item: R.MacItem(png: png)).map(\.0) == ["pc"], "an image alone: generation 1 gets nothing, 3 the image")
check(R.sends(to: [("ipad", 1), ("pc", 3)], textPayload: textPayload, item: nil).map(\.0) == ["ipad"], "no rich item read: only generation 1")
check(R.sends(to: [(String, Int)](), textPayload: textPayload, item: rich).isEmpty, "nobody subscribed: nothing")

// MARK: - A device's kind 32

check(R.fromDevice(data(#"{"text":"hi"}"#), offered: 3) == nil && R.fromDevice(data("{}"), offered: 3) == nil, "text alone or a subscription: generation 1's rules")
check(R.fromDevice(data(#"{"stop":true,"html":"<p>x</p>"}"#), offered: 3) == nil && R.fromDevice(data("x"), offered: 3) == nil, "a stop, or nothing that decodes")
let fromPC = Wire.encode(Clipboard(text: "Hi", image: png, html: "<p>Hi</p>", rtf: data("{\\rtf1 Hi}")))
var expected = R.DeviceItem(text: "Hi", html: "<p>Hi</p>", rtf: data("{\\rtf1 Hi}"), image: png, imageType: "public.png")
check(R.fromDevice(fromPC, offered: 3) == expected, "generation 2's: text, HTML, RTF, PNG")
check(R.fromDevice(fromPC, offered: 1) == nil, "never to a host that offers text alone")
check(R.fromDevice(Wire.encode(Clipboard(image: jpeg)), offered: 2)?.imageType == "public.jpeg", "a JPEG")
check(R.fromDevice(Wire.encode(Clipboard(text: "a", image: Data([1, 2, 3, 4, 5, 6, 7, 8, 9]))), offered: 3) == nil, "an image neither PNG nor JPEG, alone: nothing more")
check(R.fromDevice(Wire.encode(Clipboard(html: "")), offered: 3) == nil, "empty HTML: nothing")
let files = ClipboardFiles(files: [DragOffer.File(name: "a.txt", size: 3), DragOffer.File(name: "Folder", size: 9, folder: true)], transfers: [41, 42])
let fd = R.fromDevice(Wire.encode(Clipboard(text: "a.txt", files: files)), offered: 3)
check(fd?.transfers == [41, 42] && fd?.folders == [42] && fd?.names == [41: "a.txt", 42: "Folder"] && fd?.text == "a.txt", "generation 3's: transfers, which are folders, their names")
check(R.fromDevice(Wire.encode(Clipboard(text: "a.txt", files: files)), offered: 2) == nil, "files to a host that offers 2: nothing more")
let mismatched = R.fromDevice(Wire.encode(Clipboard(files: ClipboardFiles(files: [DragOffer.File(name: "x", size: 1, folder: true)], transfers: [1, 2]))), offered: 3)
check(mismatched?.transfers == [1, 2] && mismatched?.folders == [] && mismatched?.names == [:], "files that do not line up with the transfers: no folder unpacked, no name taken")
check(R.fromDevice(Wire.encode(Clipboard(files: ClipboardFiles(transfers: [5, 5, 6]))), offered: 3)?.transfers == [5, 6], "a transfer named twice: once")
check(R.fromDevice(Wire.encode(Clipboard(files: ClipboardFiles(transfers: Array(1...257)))), offered: 3) == nil
      && R.fromDevice(Wire.encode(Clipboard(files: ClipboardFiles(transfers: Array(1...256)))), offered: 3)?.transfers.count == 256, "256 files at most")
check(R.fromDevice(Wire.encode(Clipboard(text: long, html: "<p>x</p>")), offered: 3)?.text == nil, "text over the cap does not ride along")
check(!R.isPNG(Data([0x89, 0x50, 0x4E, 0x47, 0, 0, 0, 0, 1])), "\\x89PNG without the rest of the signature is not a PNG")
check(R.isPNG(png) && !R.isPNG(Data(png.prefix(7))) && R.isJPEG(jpeg) && !R.isJPEG(Data([0xFF, 0xD8])) && !R.isPNG(jpeg), "the signatures")

// MARK: - The device's copied files on the Mac

typealias S = R.StagedSet
let day = R.maxAge
check(R.prune([S(name: "a", bytes: 1, createdAt: 100)], now: 100).isEmpty, "the one copy stays")
check(Set(R.prune([S(name: "a", bytes: 1, createdAt: 100), S(name: "b", bytes: 1, createdAt: 200), S(name: "c", bytes: 1, createdAt: 300)], now: 300)) == ["a"],
      "the newest two stay")
check(R.prune([S(name: "a", bytes: 1, createdAt: 0)], now: day + 1) == ["a"], "a day old: gone, even the newest")
check(Set(R.prune([S(name: "a", bytes: 600 << 20, createdAt: 1), S(name: "b", bytes: 600 << 20, createdAt: 2)], now: 2)) == ["a"], "over 1 GiB together: the older goes")
check(R.prune([S(name: "b", bytes: 2 << 30, createdAt: 2)], now: 2).isEmpty, "never the newest for the cap")
check(R.takesSet(bytes: [1, 2, 3]) && R.takesSet(bytes: [R.maxSetBytes]) && !R.takesSet(bytes: [R.maxSetBytes, 1]) && !R.takesSet(bytes: [.max, 2]),
      "a copy of 512 MB at most (and no overflow)")
for _ in 0..<2_000 {
    let sets = (0..<Int.random(in: 0...6, using: &rng)).map { i in S(name: "s\(i)", bytes: UInt64.random(in: 0...(700 << 20), using: &rng), createdAt: Double.random(in: 0...200_000, using: &rng)) }
    let now = 200_000.0
    let gone = Set(R.prune(sets, now: now))
    let kept = sets.filter { !gone.contains($0.name) }
    let newest = sets.max { ($0.createdAt, $0.name) < ($1.createdAt, $1.name) }
    let ok = kept.count <= R.keptSets && kept.allSatisfy { now - $0.createdAt <= day }
        && (kept.count <= 1 || kept.reduce(UInt64(0)) { $0 + $1.bytes } <= R.maxStagedBytes)
        && (newest.map { now - $0.createdAt > day || !gone.contains($0.name) } ?? true)
        && gone.isSubset(of: Set(sets.map(\.name)))
    if !ok { check(false, "random prune: \(sets) → gone \(gone)"); break }
}
check(true, "2,000 random prunes: two at most, a day at most, 1 GiB unless one, never the newest within a day")

print(failures == 0 ? "\(checks) checks, 0 failed" : "\(failures) FAILED of \(checks)")
exit(failures == 0 ? 0 : 1)
